const UI: Record<Lang, Record<UiKey, string>> = { es, en }

export function useTranslations(lang: Lang) {
  return (key: UiKey, vars: Record<string, string | number> = {}): string =>
    Object.entries(vars).reduce((text, [name, value]) => text.replace(`{${name}}`, String(value)), UI[lang][key])
}

/** Textos que usa el código del navegador (buscador y estado sin conexión). */
export function clientStrings(lang: Lang, prefix: string): Record<string, string> {
  return Object.fromEntries(Object.entries(UI[lang]).filter(([key]) => key.startsWith(prefix)))
}
